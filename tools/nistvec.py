#!/usr/bin/env python3
"""nistvec — NIST's published SHA-1 and HMAC-SHA1 vectors, as burrow rows.

    python3 -I tools/nistvec.py extract CAVP_DIR > ci/vectors/nist-sha1.rsp
    python3 -I tools/nistvec.py module ci/vectors/nist-sha1.rsp > src/sha1vec/sha1vec.lu
    python3 -I tools/nistvec.py --check ci/vectors/nist-sha1.rsp src/sha1vec/sha1vec.lu

`extract` copies records verbatim from NIST's CAVP files (docs/SOURCES.md
holds the archives' digests): every record of SHA1ShortMsg.rsp (lengths 0
to 64 bytes, every padding boundary), the first four of SHA1LongMsg.rsp,
and the first two records of each (Klen, Tlen) group in HMAC.rsp's [L=20]
section (keys shorter than, equal to and longer than the 64-byte block;
tags truncated to 10, 12 and 16 bytes and whole). FIPS 180-4's two
examples (NIST's SHA1.pdf, "abc" and the 448-bit message) are added by
hand below, with their digests as that document prints them.

`module` turns the committed subset into src/sha1vec, which the gate
regenerates and compares byte for byte. Nothing here computes a hash.
"""
import pathlib
import sys

FIPS_EXAMPLES = [
    ("abc", "a9993e364706816aba3e25717850c26c9cd0d89d"),
    ("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq", "84983e441c3bd26ebaae4aa1f95129e5e54670f1"),
]


def records(text):
    """The `Key = value` blocks of a CAVP response file, with their section."""
    section, cur = None, {}
    for line in text.splitlines():
        line = line.strip()
        if line.startswith("["):
            section = line
            continue
        if not line or line.startswith("#"):
            if cur:
                yield section, cur
                cur = {}
            continue
        k, _, v = line.partition(" = ")
        cur[k] = v
    if cur:
        yield section, cur


def extract(d):
    d = pathlib.Path(d)
    out = ["# burrow's subset of NIST's CAVP vectors, copied verbatim by tools/nistvec.py extract.",
           "# shabytetestvectors.zip: SHA1ShortMsg.rsp (every record), SHA1LongMsg.rsp (the first four);",
           "# hmactestvectors.zip: HMAC.rsp [L=20] (the first two records of each Klen, Tlen group).",
           "# The archives' sha256 digests are in docs/SOURCES.md.", ""]
    for name, limit in (("SHA1ShortMsg.rsp", None), ("SHA1LongMsg.rsp", 4)):
        n = 0
        for _, r in records((d / "shabytetestvectors" / name).read_text()):
            if "Len" not in r:
                continue
            out += [f"[{name}]", f"Len = {r['Len']}", f"Msg = {r['Msg']}", f"MD = {r['MD']}", ""]
            n += 1
            if limit and n == limit:
                break
    seen = {}
    for section, r in records((d / "HMAC.rsp").read_text()):
        if section != "[L=20]" or "Mac" not in r:
            continue
        g = (r["Klen"], r["Tlen"])
        seen[g] = seen.get(g, 0) + 1
        if seen[g] > 2:
            continue
        out += ["[HMAC.rsp L=20]", f"Count = {r['Count']}", f"Klen = {r['Klen']}", f"Tlen = {r['Tlen']}",
                f"Key = {r['Key']}", f"Msg = {r['Msg']}", f"Mac = {r['Mac']}", ""]
    sys.stdout.write("\n".join(out))


def module(path):
    sha, mac = [], []
    for text, md in FIPS_EXAMPLES:
        sha.append(f"{text.encode().hex()} {md}")
    for section, r in records(pathlib.Path(path).read_text()):
        if section in ("[SHA1ShortMsg.rsp]", "[SHA1LongMsg.rsp]"):
            msg = "" if r["Len"] == "0" else r["Msg"]
            assert len(msg) * 4 == int(r["Len"]), r
            sha.append(f"{msg} {r['MD']}")
        elif section == "[HMAC.rsp L=20]":
            assert len(r["Key"]) == 2 * int(r["Klen"]) and len(r["Mac"]) == 2 * int(r["Tlen"]), r
            mac.append(f"{r['Key']} {r['Msg']} {r['Mac']}")
    out = ["//! member: true",
           "//!",
           "//! burrow.sha1vec — NIST's SHA-1 and HMAC-SHA1 vectors, GENERATED by",
           "//! tools/nistvec.py from ci/vectors/nist-sha1.rsp (records copied verbatim",
           "//! from NIST's CAVP archives) and FIPS 180-4's two examples. Do not edit:",
           "//! regenerate it, and the gate's vectors step compares the two byte for byte.",
           "",
           "/// `msg_hex md_hex` per vector: FIPS 180-4's examples, then the CAVP records.",
           "pub fn sha1() -> List[str] {",
           "    var v = List[str]()"]
    out += [f'    (mut v).push("{s}")' for s in sha]
    out += ["    v", "}", "",
            "/// `key_hex msg_hex mac_hex` per vector; a short `mac_hex` is a truncated tag.",
            "pub fn hmac() -> List[str] {",
            "    var v = List[str]()"]
    out += [f'    (mut v).push("{s}")' for s in mac]
    out += ["    v", "}", ""]
    return "\n".join(out)


def main():
    a = sys.argv[1:]
    if a[:1] == ["extract"]:
        extract(a[1])
    elif a[:1] == ["module"]:
        sys.stdout.write(module(a[1]))
    elif a[:1] == ["--check"]:
        want = module(a[1])
        have = pathlib.Path(a[2]).read_text()
        if have != want:
            print(f"nistvec: FAIL {a[2]} differs from a fresh generation from {a[1]}", file=sys.stderr)
            sys.exit(1)
        print(f"nistvec: {a[2]} matches a fresh generation ({want.count('(mut v).push')} vectors)")
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
